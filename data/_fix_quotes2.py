def main():
    text = DATA.read_text(encoding="utf-8")
    m = re.search(r"(window\.GRAPH_DATA\s*=\s*)(\{.*\})(\s*;?\s*)$", text, re.S)
    data = json.loads(m.group(2))
    dropped = cn_fixed = tr_fixed = 0
    drop_hit = set()
    cn_hit, tr_hit = set(), set()

    for n in data["nodes"]:
        qs = n.get("quotes") or []
        if not qs:
            continue
        out = []
        for q in qs:
            cn = (q.get("cn") or "").strip()
            hit = False
            for (bn, pref) in DROP:
                if n["name"] == bn and cn.startswith(pref):
                    dropped += 1
                    drop_hit.add((bn, pref))
                    hit = True
                    break
            if hit:
                continue
            for (bn, pref), new_cn in CN_FIX.items():
                if n["name"] == bn and cn.startswith(pref):
                    q["cn"] = new_cn
                    cn = new_cn
                    cn_fixed += 1
                    cn_hit.add((bn, pref))
                    break
            for (bn, pref), new_tr in TR_FIX.items():
                if n["name"] == bn and cn.startswith(pref):
                    q["tr"] = new_tr
                    tr_fixed += 1
                    tr_hit.add((bn, pref))
                    break
            out.append(q)
        n["quotes"] = out

    print("dropped:", dropped, "cn fixed:", cn_fixed, "tr fixed:", tr_fixed)
    miss_d = [d for d in DROP if d not in drop_hit]
    miss_c = [k for k in CN_FIX if k not in cn_hit]
    miss_t = [k for k in TR_FIX if k not in tr_hit]
    if miss_d: print("DROP no-match:", miss_d)
    if miss_c: print("CN_FIX no-match:", miss_c)
    if miss_t: print("TR_FIX no-match:", miss_t)
    # 校验：无缺译文
    miss = [(n["name"], q["cn"][:18]) for n in data["nodes"] for q in (n.get("quotes") or []) if not (q.get("tr") or "").strip()]
    print("missing tr:", len(miss), miss[:5])
    DATA.write_text(text[: m.start()] + m.group(1) + json.dumps(data, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")


if __name__ == "__main__":
    main()
